/*
XBOX_TEXTURE_LAYOUT.C

Where an Xbox texture's texels are: its format's texel size and kind, and
each mip level's size, offset and pitch. Split out of xbox_textures.c, which
decodes the texels and uploads them to OpenGL, so that a build without
OpenGL (the Wii U's) can create and lock textures too (d3d8_resources.c).
*/

#include "xbox_texture_layout.h"

#include <string.h>

